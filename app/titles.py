_WORD = re.compile(r"[A-Za-z]+")


def _fix(m: re.Match) -> str:
    w = m.group(0)
    to = TYPOS.get(w.lower())
    if not to:
        return w
    if w.isupper():
        return to.upper()
    if w[0].isupper():
        return to.capitalize()
    return to


def clean_title(title):
    """The title with its misspelled words corrected, in the same letter case; anything else unchanged."""
    if not title:
        return title
    return _WORD.sub(_fix, title)
